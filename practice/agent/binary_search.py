"""Бинарный поиск для отсортированных списков.

Предусловие: список отсортирован по возрастанию.
Реализует классический итеративный бинарный поиск с O(log n)
сложностью и возвратом индекса найденного элемента.
"""


def binary_search(arr, target):
    """Ищет `target` в отсортированном `arr`.

    Возвращает индекс элемента, если он найден, иначе -1.
    Если элемент встречается несколько раз — найден будет любой
    из них (функция не гарантирует первый или последний).
    """
    left, right = 0, len(arr) - 1

    while left <= right:
        mid = (left + right) // 2

        if arr[mid] == target:
            return mid
        elif arr[mid] < target:
            left = mid + 1
        else:
            right = mid - 1

    return -1


if __name__ == "__main__":
    # Базовые тесты

    # 1. Элемент есть в массиве
    assert binary_search([1, 3, 5, 7, 9, 11], 7) == 3

    # 2. Элемент отсутствует
    assert binary_search([1, 3, 5, 7, 9, 11], 4) == -1

    # 3. Пустой массив
    assert binary_search([], 1) == -1

    # 4. Один элемент, найден
    assert binary_search([5], 5) == 0

    # 5. Один элемент, не найден
    assert binary_search([5], 3) == -1

    # 6. Первый и последний элементы
    assert binary_search([1, 2, 3], 1) == 0
    assert binary_search([1, 2, 3], 3) == 2

    # 7. Дубликаты — результат не обязан быть первым вхождением
    result = binary_search([2, 2, 2, 2], 2)
    assert 0 <= result <= 3

    # 8. Дробные числа
    assert binary_search([0.1, 0.5, 1.0], 0.5) == 1

    # 9. Неотсортированный массив — результат неопределён (не -1 на существующем)
    # (это не гарантия корректности поиска в неотсортированных данных,
    #  а лишь фиксация того, что предусловие не соблюдено)
    try:
        binary_search([3, 1, 2], 1)
    except IndexError:
        pass  # недопустимый вход, но это вне контракта функции

    # 10. Строки (по алфавиту)
    assert binary_search(["a", "b", "c", "d"], "d") == 3

    print("Все тесты прошли успешно.")
    print("Пример: binary_search([1, 3, 5, 7, 9], 7) =",
          binary_search([1, 3, 5, 7, 9], 7))